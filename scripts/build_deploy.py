#!/usr/bin/env python3
"""Build an upload-ready copy of the portfolio for Apache shared hosting.

    npm run deploy                      # CSS build + this script (default URL)
    python3 scripts/build_deploy.py --base-url https://example.ac.th/portfolio/

What it does
  1. Copies site/ to deploy/ (the folder to upload with FTP / cPanel).
  2. If --base-url differs from the primary address, rewrites it in SEO
     tags, JSON-LD, sitemap, robots.txt and app.js.
  3. Adds ?v=<hash> to the CSS/JS links so browsers fetch new versions
     right after an update.
  4. Writes an .htaccess (compression, caching, security headers) that
     leaves /projects/ (Precision QC) alone.
  5. Packs everything into deploy/../portfolio-deploy.zip.

Run `npm run build` first so assets/css/tailwind.css is current
(`npm run deploy` does both).
"""

from __future__ import annotations

import argparse
import hashlib
import re
import shutil
import zipfile
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "site"
# site/ already uses the primary address (also the canonical for GitHub Pages).
SOURCE_URL = "https://kittiphun.rut.mcupr.ac.th/"
DEFAULT_BASE_URL = SOURCE_URL

# Files whose absolute URLs point at the site itself.
URL_FILES = ["index.html", "sitemap.xml", "robots.txt", "assets/js/app.js"]
# GitHub Pages only; not needed on Apache.
SKIP = {".nojekyll"}

HTACCESS = """# Kittiphun Ruttanakorn — portfolio (generated by scripts/build_deploy.py)
# Rules below skip /projects/ so Precision QC keeps its own settings.

DirectoryIndex index.html
Options -Indexes
AddDefaultCharset utf-8
AddType application/json .json
AddType image/svg+xml .svg
AddType image/webp .webp

<If "%{REQUEST_URI} !~ m#^/projects/#">
  <IfModule mod_deflate.c>
    AddOutputFilterByType DEFLATE text/html text/css text/plain application/javascript application/json application/xml image/svg+xml
  </IfModule>

  <IfModule mod_expires.c>
    ExpiresActive On
    # Pages and content data: always revalidate so edits show at once.
    ExpiresByType text/html "access plus 0 seconds"
    ExpiresByType application/json "access plus 0 seconds"
    # CSS/JS are linked with ?v=<hash>, so they can be cached for a long time.
    ExpiresByType text/css "access plus 1 year"
    ExpiresByType application/javascript "access plus 1 year"
    ExpiresByType image/jpeg "access plus 1 month"
    ExpiresByType image/png "access plus 1 month"
    ExpiresByType image/webp "access plus 1 month"
  </IfModule>

  <IfModule mod_headers.c>
    Header set X-Content-Type-Options "nosniff"
    Header set Referrer-Policy "strict-origin-when-cross-origin"
    Header set X-Frame-Options "SAMEORIGIN"
  </IfModule>
</If>
"""


def short_hash(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()[:10]


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--base-url", default=DEFAULT_BASE_URL, help=f"public URL of the site (default {DEFAULT_BASE_URL})")
    ap.add_argument("--out", default="deploy", help="output folder (default deploy/)")
    ap.add_argument("--no-zip", action="store_true", help="skip creating the .zip")
    args = ap.parse_args()

    base = args.base_url.rstrip("/") + "/"
    out = (ROOT / args.out).resolve()
    if out == SITE or SITE in out.parents:
        raise SystemExit("--out must not be inside site/")

    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(SITE, out, ignore=lambda d, names: [n for n in names if n in SKIP])

    for rel in URL_FILES:
        f = out / rel
        f.write_text(f.read_text(encoding="utf-8").replace(SOURCE_URL, base), encoding="utf-8")

    sitemap = out / "sitemap.xml"
    sitemap.write_text(re.sub(r"<lastmod>[^<]*</lastmod>", f"<lastmod>{date.today().isoformat()}</lastmod>",
                              sitemap.read_text(encoding="utf-8")), encoding="utf-8")

    # Cache-busting: assets/css/x.css -> assets/css/x.css?v=<hash>
    index = out / "index.html"
    html = index.read_text(encoding="utf-8")
    html = re.sub(r'((?:href|src)=")(assets/(?:css|js)/[^"?]+\.(?:css|js))(")',
                  lambda m: f'{m.group(1)}{m.group(2)}?v={short_hash(out / m.group(2))}{m.group(3)}', html)
    index.write_text(html, encoding="utf-8")

    (out / ".htaccess").write_text(HTACCESS, encoding="utf-8")

    files = sorted(p for p in out.rglob("*") if p.is_file())
    size = sum(p.stat().st_size for p in files)
    print(f"Built {out.relative_to(ROOT)}/ for {base}: {len(files)} files, {size / 1024 / 1024:.1f} MB")

    if not args.no_zip:
        zpath = out.parent / "portfolio-deploy.zip"
        with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
            for p in files:
                z.write(p, p.relative_to(out).as_posix())
        print(f"Packed {zpath.relative_to(ROOT)} ({zpath.stat().st_size / 1024 / 1024:.1f} MB)")

    if base != SOURCE_URL:
        leftover = [rel for rel in URL_FILES if SOURCE_URL in (out / rel).read_text(encoding="utf-8")]
        if leftover:
            raise SystemExit(f"Primary URL still present in: {', '.join(leftover)}")


if __name__ == "__main__":
    main()
